CREATE TABLE IF NOT EXISTS payment_attempts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id VARCHAR(40) NOT NULL,
  organization_id BIGINT UNSIGNED NOT NULL,
  mobile_user_id BIGINT UNSIGNED NOT NULL,
  provider VARCHAR(40) NOT NULL DEFAULT 'reservepay',
  merchant_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  external_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider_reference VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
  payment_session_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  amount_minor BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'THB',
  state ENUM('creating','pending','unknown','paid','failed','expired','cancelled','review') NOT NULL DEFAULT 'creating',
  provider_status VARCHAR(40) NULL,
  provider_expires_at DATETIME NULL,
  paid_at DATETIME NULL,
  last_checked_at DATETIME NULL,
  next_check_at DATETIME NULL,
  lease_until DATETIME NULL,
  lease_token CHAR(36) NULL,
  retry_count INT UNSIGNED NOT NULL DEFAULT 0,
  last_error_code VARCHAR(80) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_attempt_public (public_id),
  UNIQUE KEY uq_attempt_org_id (organization_id, id),
  UNIQUE KEY uq_attempt_external (provider, merchant_id, external_id),
  UNIQUE KEY uq_attempt_reference (provider, merchant_id, provider_reference),
  UNIQUE KEY uq_attempt_session (provider, merchant_id, payment_session_id),
  UNIQUE KEY uq_attempt_idempotency (organization_id, mobile_user_id, idempotency_key),
  KEY idx_attempt_recovery (organization_id, state, next_check_at),
  CONSTRAINT fk_attempt_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
  CONSTRAINT fk_attempt_user FOREIGN KEY (mobile_user_id) REFERENCES mobile_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
