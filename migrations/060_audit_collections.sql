CREATE TABLE IF NOT EXISTS audit_collections (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  organization_id BIGINT UNSIGNED NOT NULL,
  market_id BIGINT UNSIGNED NOT NULL,
  created_by_admin_id BIGINT UNSIGNED NOT NULL,
  audit_check_id BIGINT UNSIGNED NULL,
  payment_id BIGINT UNSIGNED NULL,
  public_id VARCHAR(40) NOT NULL,
  idempotency_key VARCHAR(160) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  customer_reference_enc TEXT NULL,
  note_enc TEXT NULL,
  lines_json JSON NOT NULL,
  subtotal_amount DECIMAL(12,2) NOT NULL,
  vat_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  total_amount DECIMAL(12,2) NOT NULL,
  qr_payload_enc TEXT NULL,
  qr_image_url_enc TEXT NULL,
  status ENUM('pending','processing','paid','failed','cancelled') NOT NULL DEFAULT 'pending',
  proof_enc MEDIUMTEXT NULL,
  proof_mime VARCHAR(30) NULL,
  proof_uploaded_at DATETIME NULL,
  reviewed_by_admin_id BIGINT UNSIGNED NULL,
  paid_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_audit_collection_reference (public_id),
  UNIQUE KEY uq_audit_collection_request (organization_id, created_by_admin_id, idempotency_key),
  UNIQUE KEY uq_audit_collection_check (audit_check_id),
  UNIQUE KEY uq_audit_collection_payment (payment_id),
  KEY idx_audit_collections_market (organization_id, market_id, status, created_at),
  CONSTRAINT fk_audit_collections_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
  CONSTRAINT fk_audit_collections_market FOREIGN KEY (market_id) REFERENCES markets(id),
  CONSTRAINT fk_audit_collections_actor FOREIGN KEY (created_by_admin_id) REFERENCES admin_users(id),
  CONSTRAINT fk_audit_collections_check FOREIGN KEY (audit_check_id) REFERENCES audit_checks(id),
  CONSTRAINT fk_audit_collections_payment FOREIGN KEY (payment_id) REFERENCES payments(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
